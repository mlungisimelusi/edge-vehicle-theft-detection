#!/usr/bin/env python3
"""
Creates the shared secrets for one installation:

    gateway/secrets.json
        lora_aes_key_hex   128-bit AES key used to decrypt/verify LoRa packets
        dashboard_pin      PIN required to arm/disarm a vehicle on the dashboard

    01_Mobile_Node_ESP32/esp32_mobile_node/lora_key.h
        the same AES key as a C array, compiled into the ESP32 firmware

Run once, on the computer you flash the ESP32 from:
    python generate_secrets.py
Then copy secrets.json to the Pi's gateway/ folder and flash the ESP32.
Both files are listed in .gitignore and must never be committed or shared.

Options:
    --force        overwrite existing files (a new key means the ESP32 must
                   be reflashed, or the gateway will reject all its packets)
    --pin 482913   choose the dashboard PIN instead of a random one
"""

import argparse
import json
import os
import secrets
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SECRETS_JSON = os.path.join(HERE, "secrets.json")
KEY_HEADER = os.path.normpath(os.path.join(HERE, "..", "..", "01_Mobile_Node_ESP32",
                                           "esp32_mobile_node", "lora_key.h"))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--pin", help="dashboard PIN (4-8 digits); random if omitted")
    args = ap.parse_args()

    if os.path.exists(SECRETS_JSON) and not args.force:
        print(f"{SECRETS_JSON} already exists. Use --force to replace it "
              f"(then reflash the ESP32 with the new lora_key.h).")
        return 1

    pin = args.pin or f"{secrets.randbelow(10**6):06d}"
    if not (pin.isdigit() and 4 <= len(pin) <= 8):
        print("The PIN must be 4-8 digits.")
        return 1

    key = secrets.token_bytes(16)
    with open(SECRETS_JSON, "w", encoding="utf-8") as fh:
        json.dump({"lora_aes_key_hex": key.hex(), "dashboard_pin": pin}, fh, indent=2)

    c_bytes = ", ".join(f"0x{b:02X}" for b in key)
    os.makedirs(os.path.dirname(KEY_HEADER), exist_ok=True)
    with open(KEY_HEADER, "w", encoding="utf-8") as fh:
        fh.write("// Generated by gateway/generate_secrets.py — DO NOT COMMIT OR SHARE.\n"
                 "// Must match lora_aes_key_hex in the gateway's secrets.json.\n"
                 "#pragma once\n"
                 "#include <stdint.h>\n"
                 f"static const uint8_t LORA_AES_KEY[16] = {{ {c_bytes} }};\n")

    print(f"Wrote {SECRETS_JSON}")
    print(f"Wrote {KEY_HEADER}")
    print(f"Dashboard arm/disarm PIN: {pin}  (also stored in secrets.json)")
    print("Next: copy secrets.json to the Pi's gateway/ folder, and reflash the ESP32.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
